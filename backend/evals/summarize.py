"""Build the consolidated evaluation report (``evals/REPORT.md``) from saved run artifacts.

Usage (from ``backend/``)::

    python -m evals.summarize            # writes evals/REPORT.md
    python -m evals.summarize --check    # exit 1 if REPORT.md is out of date

Every number in the report is read from the JSON files that ``python -m evals.run_evals`` wrote, so the
report can be regenerated and audited instead of being typed by hand.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

EVALS_DIR = Path(__file__).resolve().parent
RESULTS_DIR = EVALS_DIR / "results"
REPORT_PATH = EVALS_DIR / "REPORT.md"


@dataclass(frozen=True)
class Run:
    """One saved evaluation run shown in the report."""

    key: str
    title: str
    split: str
    path: Path


RUNS: tuple[Run, ...] = (
    Run("ollama", "Local · Ollama `qwen3.5:9b`", "golden", RESULTS_DIR / "ollama" / "final.json"),
    Run("groq", "Hosted · Groq `openai/gpt-oss-120b`", "golden", RESULTS_DIR / "groq" / "final.json"),
    Run("ollama-dev", "Local · Ollama `qwen3.5:9b`", "dev", RESULTS_DIR / "ollama" / "dev" / "final.json"),
    Run("groq-dev", "Hosted · Groq `openai/gpt-oss-120b`", "dev", RESULTS_DIR / "groq" / "dev" / "final.json"),
)
BASELINE = RESULTS_DIR / "baseline.json"
CATEGORIES = ("generation", "follow_up", "optimize", "debug", "guardrail")


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def _ratio(block: dict[str, Any] | None) -> str:
    if not block or not block.get("cases"):
        return "–"
    return f"{block['passed']}/{block['cases']} ({100 * block['accuracy']:.1f}%)"


def _secs(value: Any) -> str:
    return f"{value:.1f} s" if isinstance(value, int | float) else "–"


def _link(path: Path) -> str:
    rel = path.relative_to(EVALS_DIR).with_suffix(".md")
    return f"[`{rel}`]({rel})"


def _headline(runs: list[tuple[Run, dict[str, Any]]]) -> list[str]:
    rows = [
        "| Run | Split | All cases | Execution accuracy | Held-out execution | Guardrails | Optimize | Debug | Intent | "
        "Avg LLM turn (p90) | Structured-output fallbacks | Agent errors |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for run, data in runs:
        s, meta = data["summary"], data["meta"]
        cats = s.get("categories", {})
        lat = s.get("latency", {})
        so = meta.get("structured_output", {})
        rows.append(
            f"| {run.title} | {run.split} ({meta['golden'].get('cases_run')}) | **{_ratio(s.get('overall'))}** | "
            f"**{_ratio(s.get('execution_accuracy'))}** | {_ratio(s.get('held_out_execution_accuracy'))} | "
            f"{_ratio(s.get('guardrail_compliance'))} | {_ratio(cats.get('optimize'))} | {_ratio(cats.get('debug'))} | "
            f"{_ratio(s.get('intent_accuracy'))} | {_secs(lat.get('avg_llm_turn_s'))} ({_secs(lat.get('p90_llm_turn_s'))}) | "
            f"{so.get('fallbacks', 0)} | {s.get('agent_errors', 0)} |"
        )
    return rows


def _categories(run: Run, data: dict[str, Any]) -> list[str]:
    cats = data["summary"].get("categories", {})
    rows = [f"#### {run.title} – {run.split} split", "", "| Category | Passed | Avg latency per case |", "|---|---|---|"]
    for name in CATEGORIES:
        if name in cats:
            rows.append(f"| {name.replace('_', '-')} | {_ratio(cats[name])} | {_secs(cats[name].get('avg_latency_s'))} |")
    return [*rows, ""]


def _failures(run: Run, data: dict[str, Any]) -> list[str]:
    failed = [case for case in data.get("cases", []) if not case.get("passed")]
    if not failed:
        return [f"- **{run.title} – {run.split}:** no failures.", ""]
    lines = [f"- **{run.title} – {run.split}:** {len(failed)} failure(s)"]
    for case in failed:
        reason = " ".join(str(case.get("reason") or "").split())[:220]
        lines.append(f"  - `{case['id']}` ({case['category']}): {case.get('question', '')!s} – {reason}")
    return [*lines, ""]


def build_report(runs: list[tuple[Run, dict[str, Any]]], baseline: dict[str, Any] | None) -> str:
    """Markdown for REPORT.md from loaded run reports (pure function, used by the tests)."""
    golden_meta = runs[0][1]["meta"] if runs else {}
    lines = [
        "# QueryPilot – evaluation report",
        "",
        "Generated by `python -m evals.summarize` from the saved run files in `backend/evals/results/`. "
        "Nothing in this file is typed by hand.",
        "",
        "## What is measured",
        "",
        "- **Golden set** (`evals/golden.json`, 38 cases): generation, multi-turn follow-ups, optimize, debug and "
        "guardrail cases, including the brief's own examples. **Dev split** (`evals/dev.json`, 21 harder cases).",
        "- **Execution accuracy:** generated SQL counts as correct when its result set equals the reference SQL's "
        "result set (rows compared as multisets; column names and order ignored; row order checked only when the "
        "question asks for an ordering or top-N).",
        "- **Held-out execution accuracy:** the same, excluding cases that mirror the brief's few-shot examples.",
        "- **Guardrails:** destructive, out-of-scope, prompt-injection and ambiguous requests must get the expected "
        "status (refused / rejected / clarification), no SQL, and the brief's exact out-of-scope sentence.",
        "- **Optimize:** the rewrite must validate, return the same rows as the original and carry suggestions. "
        "**Debug:** the corrected SQL must validate and match the reference result.",
        "- Every run checks that the database file is byte-identical afterwards (the agent is read-only).",
        "",
        "## Headline results (final code and prompts)",
        "",
        *_headline(runs),
        "",
        f"Prompt version (system prompts + mode instructions, sha256): `{str(golden_meta.get('prompts_sha256', ''))[:12]}`. "
        "Latency is wall-clock per LLM-backed turn (intent + SQL + explanation); local runs on an Apple M5 "
        "(16 GB), hosted runs over the network to Groq's free tier.",
        "",
        "**Hosted latency caveat:** Groq's free tier allows 8,000 tokens per minute per model (confirmed from the "
        "API's `x-ratelimit-*` headers during the run). The eval sends requests back to back, so the hosted "
        "latency above mostly measures that throttle; a single interactive question typically completes in a "
        "few seconds (the first cases of each hosted run took about 2-5 s). Rate-limited calls wait and retry, "
        "then fall back to `qwen/qwen3.8-27b`; they are not counted as failures unless the final answer is wrong.",
        "",
        "## By category",
        "",
    ]
    for run, data in runs:
        lines += _categories(run, data)
    lines += ["## Failures", ""]
    for run, data in runs:
        lines += _failures(run, data)
    if baseline:
        b = baseline["summary"]
        lines += [
            "## Before prompt tuning (local model)",
            "",
            f"Baseline run ({baseline['meta'].get('started_at', '')[:16]}): all cases {_ratio(b.get('overall'))}, "
            f"execution accuracy {_ratio(b.get('execution_accuracy'))}, guardrails "
            f"{_ratio(b.get('guardrail_compliance'))}. Details: [`results/baseline.md`](results/baseline.md).",
            "",
        ]
    lines += [
        "## How the prompts were tuned (honest note)",
        "",
        "Prompt rules were tuned by inspecting failures on the **dev split**; the golden set served as a "
        "regression check. One optimize rule (keep every row when turning a subquery into a join) was added "
        "after a golden-set regression, and a rule to keep WHERE filters out of JOIN conditions was added after "
        "manual testing. Neither the golden nor the dev questions appear in the prompts' few-shot examples except "
        "the brief's own public examples. Treat these numbers as indicative: the sets are small and LLM output "
        "varies slightly between runs.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "cd backend",
        "# local model (Ollama)",
        "LLM_PROVIDER=ollama .venv/bin/python -m evals.run_evals --provider ollama --model qwen3.5:9b "
        "--fast-model qwen3.5:9b --out-dir evals/results/ollama --save-as final",
        "# hosted model (needs GROQ_API_KEY)",
        ".venv/bin/python -m evals.run_evals --provider groq --model openai/gpt-oss-120b "
        "--fast-model openai/gpt-oss-20b --out-dir evals/results/groq --save-as final",
        "# add --golden evals/dev.json --out-dir evals/results/<provider>/dev for the dev split, then:",
        ".venv/bin/python -m evals.summarize",
        "```",
        "",
        "## Detailed per-run reports",
        "",
    ]
    lines += [f"- {run.title}, {run.split} split: {_link(run.path)}" for run, _ in runs]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: write REPORT.md, or with --check verify it is current."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if REPORT.md is out of date")
    args = parser.parse_args(argv)
    runs = [(run, data) for run in RUNS if (data := _load(run.path)) is not None]
    if not runs:
        print("No saved runs found under evals/results/*/final.json", file=sys.stderr)
        return 1
    report = build_report(runs, _load(BASELINE))
    if args.check:
        current = REPORT_PATH.read_text(encoding="utf-8") if REPORT_PATH.is_file() else ""
        if current != report:
            print(f"{REPORT_PATH} is out of date; run: python -m evals.summarize", file=sys.stderr)
            return 1
        print(f"{REPORT_PATH} is up to date")
        return 0
    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"Wrote {REPORT_PATH} ({len(runs)} runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
